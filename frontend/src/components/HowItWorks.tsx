import { useEffect, useState } from "react";

const STAGES = [
  ["Ingest", "Synthetic match events and 5 Hz player tracking arrive as a live feed, and stream into Microsoft Fabric."],
  ["Interpret", "Stats, pass difficulty, ball and shot speed, sprints, xG, live win probability and three story indices."],
  ["Explain", "Auditable reason codes say why a moment matters. A Narrator agent writes it up and a Verifier agent fact-checks it, as a Microsoft Agent Framework workflow."],
  ["Render", "A timed, machine-readable overlay feed that any broadcast graphics engine can draw in sync."],
  ["Personalise", "Mode, language, favourite club and player turn the same intelligence into different experiences."],
];

const TECH = [
  ["Microsoft Agent Framework", "Three agents: Narrator and Verifier (a workflow with one rewrite loop) and the Ask the match analyst with six tools"],
  ["Microsoft Foundry", "The model behind all three agents (gpt-4.1-mini)"],
  ["Microsoft Fabric", "Every event streams to an Eventhouse for live KQL queries"],
  ["Azure Container Apps", "This live app, deployed from GitHub Actions"],
  ["GitHub", "Public repo, CI on every push, container image builds"],
];

export function HowItWorks({ onClose }: { onClose: () => void }) {
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => e.key === "Escape" && onClose();
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [onClose]);
  return (
    <div className="how-backdrop" onClick={onClose}>
      <div className="how" role="dialog" aria-modal="true" aria-labelledby="how-title" onClick={(e) => e.stopPropagation()}>
        <div className="how-head">
          <h2 id="how-title">How FootieManager works</h2>
          <button onClick={onClose} aria-label="Close">
            Close
          </button>
        </div>
        <ol className="how-stages">
          {STAGES.map(([name, text]) => (
            <li key={name}>
              <strong>{name}</strong>
              <span>{text}</span>
            </li>
          ))}
        </ol>
        <h3>Built on</h3>
        <ul className="how-tech">
          {TECH.map(([name, text]) => (
            <li key={name}>
              <strong>{name}</strong>
              <span>{text}</span>
            </li>
          ))}
        </ul>
        <p className="how-note">All clubs, players and matches are synthetic, generated by our own match engine.</p>
      </div>
    </div>
  );
}

const TIPS_KEY = "footiemanager-tips-dismissed";

/** Three tips for first-time visitors (e.g. judges opening the live link). Remembered per browser. */
export function FirstVisitTips({ onHow }: { onHow: () => void }) {
  const [hidden, setHidden] = useState(() => {
    try {
      return localStorage.getItem(TIPS_KEY) === "1";
    } catch {
      return false;
    }
  });
  if (hidden) return null;
  const dismiss = () => {
    setHidden(true);
    try {
      localStorage.setItem(TIPS_KEY, "1");
    } catch {
      /* private mode: just hide for this visit */
    }
  };
  return (
    <aside className="tips" aria-label="Getting started">
      <ol>
        <li>
          <strong>One match, two viewers.</strong> Change each viewer's mode, language and favourite club to see how the
          same moment is told differently.
        </li>
        <li>
          <strong>Check the evidence.</strong> Click <em>Sources</em> on any key moment to see exactly what the AI was given.
        </li>
        <li>
          <strong>Ask the match anything.</strong> The agent shows each step it took to answer.
        </li>
      </ol>
      <div className="tips-actions">
        <button onClick={onHow}>How it works</button>
        <button onClick={dismiss} className="btn-primary">
          Got it
        </button>
      </div>
    </aside>
  );
}
